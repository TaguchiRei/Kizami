using System;
using System.Collections.Generic;
using AutoGenerated;
using Kizami.BlackBoard;
using Kizami.External;
using UsefulToolkit.BlackBoard.BlackBoard;
using UsefulToolkit.BlackBoard.Input;
using UsefulToolkit.BlackBoard.Logger;

namespace Kizami.Application
{
    /// <summary>
    /// インゲームの流れ（StageFlowState）を進めるユースケース。破壊済みの破壊対象がステージの必要な数に達し、倒した敵の数もステージの必要な数に達したら（ステージが破壊でのクリアを許すときだけ）クリアにし、
    /// ステージの失敗条件のどれかを満たしたら失敗にする。クリアと失敗はプレイ中にだけ起こり、一度決まったら変わらない。
    /// スコアは、倒した敵1体につき1点と、よい行動の追加スコアと、クリアしたときの基礎スコアの合計。クリアタイムと被ダメージは、時間をかけて準備して壊す遊び方を損なわない為、使わない。
    /// プレイ中は UI マップの Cancel（Esc）でポーズを切り替える。ポーズは時間の倍率を0にして Player マップを止め、解くとポーズ前の倍率に戻す。
    /// クリアか失敗になったら Player マップを止める。
    /// 制限時間の失敗条件があるステージでは、外から渡された実時間（Tick）で残り時間を減らし、ポーズ中は減らさない。
    /// </summary>
    public sealed class StageFlowService : IDisposable
    {
        private readonly StageFlowState _state = new();
        private readonly List<IDisposable> _subscriptions = new();
        private readonly int _clearScore;
        private readonly bool _clearsOnTargets;

        /// <summary> ステージの定義にある、クリアに必要な破壊済みの数。0 なら破壊対象すべて </summary>
        private readonly int _requiredTargetCount;

        /// <summary> ステージの定義にある、クリアに必要な倒した敵の数。0 なら敵の数を条件にしない </summary>
        private readonly int _requiredDefeatCount;
        private readonly ITimeScaleController _timeScaleController;
        private readonly ITimeScaleState _timeScaleState;
        private readonly IInputController _inputController;
        private readonly Action _onCleared;

        /// <summary> ポーズを解いたときに戻す時間の倍率 </summary>
        private float _resumeScale = 1f;

        /// <summary> 制限時間の失敗条件があるか </summary>
        private bool _hasTimeLimit;

        /// <summary>
        /// StageFlowState を StageBoard へ登録し、失敗条件の判定に使う State の変化と、ポーズの入力を購読する。
        /// </summary>
        /// <param name="blackBoard">StageFlowState の登録先と、失敗条件の判定に使う State・入力・時間の倍率の取得元</param>
        /// <param name="stage">遊ぶステージの定義</param>
        /// <param name="timeScaleController">ポーズで時間の倍率を変える操作面</param>
        /// <param name="inputController">ポーズ中とクリア・失敗のあとに Player マップを止める操作面</param>
        /// <param name="onCleared">クリアしたときに呼ぶ処理（クリアの記録とスキルの解放など）</param>
        /// <param name="sceneId">State を紐づけるシーンのビルドインデックス</param>
        public StageFlowService(IBlackBoard blackBoard, StageData stage, ITimeScaleController timeScaleController,
            IInputController inputController, Action onCleared, int sceneId)
        {
            _clearScore = stage.ClearScore;
            _clearsOnTargets = stage.ClearsOnTargets;
            _requiredTargetCount = stage.RequiredTargetCount;
            _requiredDefeatCount = stage.RequiredDefeatCount;
            _timeScaleController = timeScaleController;
            _inputController = inputController;
            _onCleared = onCleared;

            if (!blackBoard.TryGetBoard<StageBoard>(out var stageBoard, this) ||
                !blackBoard.TryGetGameState<AppBoard, ITimeScaleState>(out _timeScaleState, this) ||
                !blackBoard.TryGetGameState<InputBoard, IInputState>(out var inputState, this)) return;

            _state.SetRequiredDefeatCount(_requiredDefeatCount);
            stageBoard.RegisterSceneState<IStageFlowState>(_state, sceneId);

            foreach (var condition in stage.FailConditions)
            {
                WatchFailCondition(blackBoard, condition);
            }

            _subscriptions.Add(inputState.RegisterInput<float>(ActionMaps.UI, UIActions.Cancel, OnCancel));
        }

        /// <summary>
        /// プレイを始める。開始前のときだけ、プレイ中にしてポーズの入力を受け付ける。始めた時点ですべて破壊済みなら、そのままクリアにする。
        /// </summary>
        public void Begin()
        {
            if (_state.Phase != StagePhase.Ready) return;

            _state.SetPhase(StagePhase.Playing);
            _inputController?.EnableActionMap(ActionMaps.UI);
            TryClear();
        }

        /// <summary>
        /// 破壊対象の数と、破壊済みの数を受け取る。プレイ中に破壊済みの数が必要な数に達したらクリアにする。
        /// </summary>
        /// <param name="targetCount">ステージにある破壊対象の数</param>
        /// <param name="destroyedCount">破壊済みの破壊対象の数</param>
        public void ReportTargets(int targetCount, int destroyedCount)
        {
            var requiredCount = _requiredTargetCount > 0 ? Math.Min(_requiredTargetCount, targetCount) : targetCount;
            _state.SetTargets(targetCount, destroyedCount, requiredCount);
            TryClear();
        }

        /// <summary>
        /// 破壊対象によらず、プレイ中ならクリアにする。台本の終わりでクリアにするステージが使う。
        /// </summary>
        public void Clear()
        {
            if (_state.Phase != StagePhase.Playing) return;

            CompleteClear();
        }

        /// <summary>
        /// 倒した敵の数を足し、スコアに反映する。プレイ中のときだけ数える。必要な数に達したらクリアを判定する。
        /// </summary>
        /// <param name="count">倒した敵の数</param>
        public void AddDefeats(int count)
        {
            if (_state.Phase != StagePhase.Playing || count <= 0) return;

            _state.SetDefeatCount(_state.DefeatCount + count);
            _state.SetScore(_state.Score + count);
            TryClear();
        }

        /// <summary>
        /// よい行動の追加スコアを足す。プレイ中のときだけ足す。
        /// </summary>
        /// <param name="score">追加スコア</param>
        public void AddBonusScore(int score)
        {
            if (_state.Phase != StagePhase.Playing || score <= 0) return;

            _state.SetScore(_state.Score + score);
        }

        /// <summary>
        /// 制限時間を進める。プレイ中でポーズしていないときだけ進め、残りが0になったら失敗にする。
        /// </summary>
        /// <param name="deltaSeconds">前回から経った実時間（秒）</param>
        public void Tick(float deltaSeconds)
        {
            if (!_hasTimeLimit || _state.Phase != StagePhase.Playing || _state.IsPaused) return;

            var remaining = Math.Max(0f, _state.RemainingTime - deltaSeconds);
            _state.SetRemainingTime(remaining);
            if (remaining <= 0f) Fail(StageFailReason.TimeUp);
        }

        /// <summary>
        /// プレイ中でポーズしていなければ、ポーズする。
        /// </summary>
        public void Pause()
        {
            if (_state.Phase != StagePhase.Playing || _state.IsPaused || _timeScaleController == null ||
                _timeScaleState == null) return;

            _resumeScale = _timeScaleState.Scale;
            _timeScaleController.SetScale(0f);
            _inputController?.DisableActionMap(ActionMaps.Player);
            _state.SetPaused(true);
        }

        /// <summary>
        /// ポーズ中なら、ポーズ前の倍率に戻して Player マップを動かす。
        /// </summary>
        public void Resume()
        {
            if (!_state.IsPaused) return;

            _timeScaleController.SetScale(_resumeScale);
            _inputController?.EnableActionMap(ActionMaps.Player);
            _state.SetPaused(false);
        }

        private void OnCancel(InputContext<float> context)
        {
            if (context.Phase != InputPhase.Performed) return;

            if (_state.IsPaused)
            {
                Resume();
            }
            else
            {
                Pause();
            }
        }

        /// <summary>
        /// 失敗条件の型に応じて、判定に使う State の変化を購読する。
        /// </summary>
        private void WatchFailCondition(IBlackBoard blackBoard, StageFailCondition condition)
        {
            switch (condition)
            {
                case PlayerDeathFailCondition:
                    if (!blackBoard.TryGetSceneState<PlayerBoard, IPlayerHealthState>(out var healthState, this)) return;

                    _subscriptions.Add(healthState.RegisterOnHealthChanged((_, current) =>
                    {
                        if (current <= 0) Fail(StageFailReason.PlayerDeath);
                    }));
                    break;
                case TimeLimitFailCondition timeLimit:
                    _hasTimeLimit = true;
                    _state.SetRemainingTime(timeLimit.Seconds);
                    break;
                case null:
                    break;
                default:
                    UsefulLogger.LogError($"失敗条件 {condition.GetType().Name} の判定がない為、無視します。", this);
                    break;
            }
        }

        /// <summary>
        /// プレイ中に、必要な数の破壊対象が破壊済みで、倒した敵の数も必要な数に達しているなら、クリアにする。
        /// </summary>
        private void TryClear()
        {
            if (!_clearsOnTargets || _state.Phase != StagePhase.Playing || _state.TargetCount == 0 ||
                _state.DestroyedTargetCount < _state.RequiredTargetCount ||
                _state.DefeatCount < _state.RequiredDefeatCount) return;

            CompleteClear();
            UsefulLogger.Log("必要な数の破壊対象が破壊済みで、倒した敵の数も足りた為、クリアにしました。", this);
        }

        /// <summary>
        /// 基礎スコアを足してクリアにする。
        /// </summary>
        private void CompleteClear()
        {
            _state.SetScore(_state.Score + _clearScore);
            Finish(StagePhase.Cleared);
            _onCleared?.Invoke();
        }

        /// <summary>
        /// プレイ中のときだけ、失敗にする。
        /// </summary>
        private void Fail(StageFailReason reason)
        {
            if (_state.Phase != StagePhase.Playing) return;

            _state.SetFailReason(reason);
            Finish(StagePhase.Failed);
            UsefulLogger.Log($"失敗条件 {reason} を満たした為、失敗にしました。", this);
        }

        /// <summary>
        /// クリアか失敗にして、Player マップを止める。
        /// </summary>
        private void Finish(StagePhase phase)
        {
            _state.SetPhase(phase);
            _inputController?.DisableActionMap(ActionMaps.Player);
        }

        /// <summary>
        /// 購読を解除する。ポーズ中なら倍率を等速に戻す。ポーズ前の倍率（スローモード）は、スローモードの側が自分で戻す。
        /// </summary>
        public void Dispose()
        {
            foreach (var subscription in _subscriptions)
            {
                subscription.Dispose();
            }

            _subscriptions.Clear();

            if (!_state.IsPaused) return;

            _timeScaleController.ResetScale();
            _state.SetPaused(false);
        }
    }
}
