using System;
using System.Collections.Generic;
using AutoGenerated;
using Kizami.BlackBoard;
using Kizami.External;
using UsefulToolkit.BlackBoard.BlackBoard;
using UsefulToolkit.BlackBoard.Input;

namespace Kizami.Application
{
    /// <summary>
    /// スキル1〜3の入力を受けて、その枠に装備しているスキルの分のチャージを消費し、効果の実行役を呼ぶユースケース。強化型スキルは PlayerEnhanceService にかける。
    /// </summary>
    public sealed class SkillService : IDisposable
    {
        /// <summary> 装備枠の数 </summary>
        public const int SLOT_COUNT = 3;

        private readonly SkillData[] _slots = new SkillData[SLOT_COUNT];
        private readonly SkillSlotState _slotState = new(SLOT_COUNT);
        private readonly ChargeService _chargeService;
        private readonly PlayerEnhanceService _enhanceService;
        private readonly Action<float, float> _onBeam;
        private readonly Action<float> _onExplosion;
        private readonly Action<int> _onHeal;
        private readonly Action<float, float> _onBomb;
        private readonly Action<float, float, float> _onSweep;
        private readonly Action<float, float, float, float> _onRush;
        private readonly Func<float, bool> _onMoundBegin;
        private readonly Action _onMoundEnd;
        private readonly Func<bool> _canAct;
        private readonly Func<bool> _canRush;
        private readonly Action _onActed;
        private readonly List<IDisposable> _subscriptions = new();
        private readonly PlayerActionEvents _actionEvents;
        private readonly IPlayerHealthState _healthState;
        private int _moundSlot = -1;

        /// <param name="blackBoard">SkillSlotState の登録先と、入力・HP の取得元</param>
        /// <param name="equippedSkills">枠ごとに装備するスキル。空きの枠と、SLOT_COUNT を超えた分は無視する</param>
        /// <param name="chargeService">発動に使うチャージの消費先</param>
        /// <param name="enhanceService">強化型スキルをかける先</param>
        /// <param name="onBeam">ビームを出す関数。引数は長さ（m）と半径（m）</param>
        /// <param name="onExplosion">爆発を出す関数。引数は半径（m）</param>
        /// <param name="onHeal">HP を回復する関数。引数は回復量</param>
        /// <param name="onBomb">爆弾を投げる関数。引数は投げる距離（m）と爆発の半径（m）</param>
        /// <param name="onSweep">正面を横長に削る関数。引数は横幅（m）、奥行き（m）、1m あたりに減る強さ</param>
        /// <param name="onRush">突進する関数。引数は距離（m）、所要時間（秒）、削る半径（m）、1m あたりに減る強さ</param>
        /// <param name="onMoundBegin">ボクセルを盛り始める関数。引数は球の半径（m）。盛り始められたら true を返す</param>
        /// <param name="onMoundEnd">ボクセルを盛るのを止める関数</param>
        /// <param name="canRush">突進を始められるかを返す関数。攻走でだけ使う</param>
        /// <param name="canAct">スキルを出せる攻撃間隔が経っているかを返す関数。通常攻撃と共有する</param>
        /// <param name="onActed">スキルを出したときに呼ぶ関数。通常攻撃と共有する攻撃間隔を数え直す</param>
        /// <param name="actionEvents">スキルの発動とチャージの消費を流す先</param>
        /// <param name="sceneId">State を紐づけるシーンのビルドインデックス</param>
        public SkillService(IBlackBoard blackBoard, IReadOnlyList<SkillData> equippedSkills,
            ChargeService chargeService, PlayerEnhanceService enhanceService, Action<float, float> onBeam,
            Action<float> onExplosion, Action<int> onHeal, Action<float, float> onBomb, Action<float, float, float> onSweep,
            Action<float, float, float, float> onRush, Func<float, bool> onMoundBegin, Action onMoundEnd, Func<bool> canRush, Func<bool> canAct, Action onActed, PlayerActionEvents actionEvents,
            int sceneId)
        {
            _actionEvents = actionEvents;
            _chargeService = chargeService;
            _enhanceService = enhanceService;
            _onBeam = onBeam;
            _onExplosion = onExplosion;
            _onHeal = onHeal;
            _onBomb = onBomb;
            _onSweep = onSweep;
            _onRush = onRush;
            _onMoundBegin = onMoundBegin;
            _onMoundEnd = onMoundEnd;
            _canRush = canRush;
            _canAct = canAct;
            _onActed = onActed;

            var count = Math.Min(equippedSkills.Count, SLOT_COUNT);
            for (var i = 0; i < count; i++)
            {
                _slots[i] = equippedSkills[i];
                if (_slots[i] != null) _slotState.SetSlot(i, _slots[i].Cost, _slots[i].Icon, _slots[i].DisplayName);
            }

            if (!blackBoard.TryGetBoard<PlayerBoard>(out var playerBoard, this) ||
                !blackBoard.TryGetGameState<InputBoard, IInputState>(out var inputState, this) ||
                !blackBoard.TryGetSceneState<PlayerBoard, IPlayerHealthState>(out _healthState, this)) return;

            playerBoard.RegisterSceneState<ISkillSlotState>(_slotState, sceneId);

            _subscriptions.Add(inputState.RegisterInput<float>(ActionMaps.Player, PlayerActions.Skill1,
                context => OnSkill(context, 0)));
            _subscriptions.Add(inputState.RegisterInput<float>(ActionMaps.Player, PlayerActions.Skill2,
                context => OnSkill(context, 1)));
            _subscriptions.Add(inputState.RegisterInput<float>(ActionMaps.Player, PlayerActions.Skill3,
                context => OnSkill(context, 2)));
        }

        /// <summary>
        /// 枠にスキルがあり、通常攻撃と共有する攻撃間隔が経っていて、その消費量だけチャージを消費できたら、スキルの発動とチャージの消費を通知して、効果を出す。
        /// 回復は、HP が0のときと最大のときは発動せず、チャージも消費しない。造山は、押した枠を離すまで盛り続け、視線が何にも当たらないときは発動せず、チャージも消費しない。攻走は、突進を始められないときは発動せず、チャージも消費しない。
        /// </summary>
        private void OnSkill(InputContext<float> context, int slot)
        {
            var skill = _slots[slot];
            if (skill == null) return;

            if (context.Phase == InputPhase.Canceled)
            {
                if (_moundSlot == slot) EndMound();
                return;
            }

            if (context.Phase != InputPhase.Performed) return;
            if (_canAct != null && !_canAct()) return;
            if (skill.Effect == SkillEffect.Heal && !CanHeal()) return;
            if (skill.Effect == SkillEffect.Rush && _canRush != null && !_canRush()) return;
            if (skill.Effect == SkillEffect.Mound && (_onMoundBegin == null || !_onMoundBegin(skill.Radius))) return;
            if (!_chargeService.TryConsume(skill.Cost))
            {
                if (skill.Effect == SkillEffect.Mound) _onMoundEnd?.Invoke();
                return;
            }

            if (skill.Effect == SkillEffect.Mound) _moundSlot = slot;

            _onActed?.Invoke();

            _actionEvents.Raise(new PlayerActionNotice(PlayerActionKind.SkillUsed, skill.DisplayName));
            _actionEvents.Raise(new PlayerActionNotice(PlayerActionKind.ChargeSpent, amount: skill.Cost));

            if (skill.IsEnhancement)
            {
                _enhanceService.Begin(skill);
                return;
            }

            switch (skill.Effect)
            {
                case SkillEffect.Beam:
                    _onBeam?.Invoke(skill.Length, skill.Radius);
                    break;
                case SkillEffect.Explosion:
                    _onExplosion?.Invoke(skill.Radius);
                    break;
                case SkillEffect.Heal:
                    _onHeal?.Invoke(skill.HealAmount);
                    break;
                case SkillEffect.Bomb:
                    _onBomb?.Invoke(skill.Distance, skill.Radius);
                    break;
                case SkillEffect.Sweep:
                    _onSweep?.Invoke(skill.Width, skill.Depth, skill.Falloff);
                    break;
                case SkillEffect.Rush:
                    _onRush?.Invoke(skill.Distance, skill.Duration, skill.Radius, skill.Falloff);
                    break;
            }
        }

        private void EndMound()
        {
            _moundSlot = -1;
            _onMoundEnd?.Invoke();
        }

        private bool CanHeal()
        {
            return _healthState != null && _healthState.Current > 0 && _healthState.Current < _healthState.Max;
        }

        public void Dispose()
        {
            foreach (var subscription in _subscriptions)
            {
                subscription.Dispose();
            }

            _subscriptions.Clear();
        }
    }
}
