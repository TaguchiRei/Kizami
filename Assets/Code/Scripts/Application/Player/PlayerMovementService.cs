using System;
using System.Collections.Generic;
using AutoGenerated;
using Kizami.BlackBoard;
using Kizami.External;
using UnityEngine;
using UsefulToolkit.BlackBoard.BlackBoard;
using UsefulToolkit.BlackBoard.Input;

namespace Kizami.Application
{
    /// <summary>
    /// 入力と視線の向き、触れている物から、プレイヤーの移動モード・ワールド空間の目標速度・ジャンプを決めるユースケース。
    /// 入力イベントと打ち上げの要求では値を記録し、判定と State の更新は Step で行う。
    /// 物理への反映と加減速の補間は PlayerMovementAdapterBase が行う。
    /// </summary>
    public sealed class PlayerMovementService : IPlayerMovementController, IDisposable
    {
        private readonly PlayerMovementState _state = new();
        private readonly List<IDisposable> _subscriptions = new();

        private IOperationSettingState _settingState;
        private PlayerActionEvents _actionEvents;
        private PlayerParameterData _parameters;
        private IDisposable _contactStateWaiter;
        private IPlayerContactState _contactState;

        /// <summary> 移動入力。x が右、y が前を正とし、長さは1以下 </summary>
        private Vector2 _moveInput;

        private bool _isSprintHeld;
        private bool _isSprintToggled;

        /// <summary> 次の Step で処理するジャンプ入力があるか </summary>
        private bool _isJumpRequested;

        /// <summary> ジャンプボタンを押しているか </summary>
        private bool _isJumpHeld;

        /// <summary> ジャンプしてから、長押しの効果が残っている時間（秒）。ジャンプしていないときは 0 </summary>
        private float _jumpHoldRemaining;

        /// <summary> 視線の向きを水平面へ投影した向き。視線が真上・真下を向いている間は直前の値を保つ </summary>
        private Vector3 _viewForward = Vector3.forward;

        /// <summary> 上下を含む視線の向き（正規化済み） </summary>
        private Vector3 _viewDirection = Vector3.forward;

        /// <summary> 壁走りの残りの持ち時間（秒）。着地で最大値に戻る </summary>
        private float _wallRunTimeRemaining;

        /// <summary> 最後に触れていた壁の法線。壁が途切れて壁走りの途中でとどまっている間も、壁キックと離れる入力の判定に使う </summary>
        private Vector3 _wallNormal;

        /// <summary> 壁から離れようとする入力が続いている時間（秒） </summary>
        private float _wallDetachInputTime;

        /// <summary> 壁ジャンプ後、壁との接触が一度切れるまで true になり、その間は壁走りへの再突入を止める </summary>
        private bool _isWaitingWallRelease;

        /// <summary> 次の Step で処理する打ち上げの上向きの打ち出し速度（m/s）。要求がなければ0 </summary>
        private float _launchSpeed;

        /// <summary> 次の Step で処理する打ち上げの水平の打ち出し速度（m/s）。要求がなければゼロ </summary>
        private Vector3 _launchHorizontalVelocity;

        /// <summary> 次の Step で処理する突進の要求があるか </summary>
        private bool _isRushRequested;

        /// <summary> 要求された突進の向き（水平、正規化済み） </summary>
        private Vector3 _rushDirection;

        /// <summary> 要求された突進の距離（m） </summary>
        private float _rushDistance;

        /// <summary> 要求された突進の所要時間（秒） </summary>
        private float _rushDuration;

        /// <summary> 飛びの終わりに続けて飛ぶ向きと距離。続けないときはゼロ </summary>
        private Vector3 _followFlightDisplacement;

        /// <summary> 続けて飛ぶ所要時間（秒） </summary>
        private float _followFlightDuration;

        /// <summary> 実行中の突進の速度（m/s） </summary>
        private Vector3 _warpVelocity;

        /// <summary> 実行中の突進の残りの所要時間（秒） </summary>
        private float _warpTimeRemaining;

        /// <summary> 言葉をつかんでいる間は true になり、その間は移動モードを Aiming にして静止する </summary>
        private bool _isHoldingWord;

        /// <summary> 羽天轟号の使用中は true になり、その間は移動モードを Aiming にして静止する </summary>
        private bool _isSkyBeamActive;

        /// <summary> 言葉をつかんでいるか </summary>
        public bool IsHoldingWord => _isHoldingWord;

        /// <summary> ダッシュ入力の受け付け方に応じて、押下中またはトグルの状態を返す </summary>
        private bool IsSprinting => _settingState.SprintInputMode == SprintInputMode.Hold
            ? _isSprintHeld
            : _isSprintToggled;

        /// <summary> 地面に触れているか </summary>
        private bool IsGrounded => _contactState != null && (_contactState.Contacts & PlayerContact.Ground) != 0;

        /// <summary> 足元の近くに地面があるか </summary>
        private bool IsNearGround => _contactState != null && (_contactState.Contacts & PlayerContact.NearGround) != 0;

        /// <summary> 空中で壁に触れているか。地面と壁の両方に触れているときは地面を優先して false </summary>
        private bool IsTouchingWallInAir => _contactState != null && !IsGrounded &&
                                            (_contactState.Contacts & PlayerContact.Wall) != 0;

        /// <summary>
        /// PlayerMovementState を PlayerBoard へ登録し、入力を受け取り始める。Initialize より前の Step は何もしない。
        /// </summary>
        /// <param name="blackBoard">PlayerMovementState の登録先と、入力・ダッシュ入力の受け付け方・触れている物の取得元</param>
        /// <param name="parameters">移動のパラメータ</param>
        /// <param name="actionEvents">ジャンプ・壁走り・壁キックを流す先</param>
        /// <param name="sceneId">State を紐づけるシーンのビルドインデックス</param>
        public void Initialize(IBlackBoard blackBoard, PlayerParameterData parameters, PlayerActionEvents actionEvents,
            int sceneId)
        {
            _actionEvents = actionEvents;
            _parameters = parameters;
            _wallRunTimeRemaining = parameters.WallRunDuration;

            if (!blackBoard.TryGetBoard<PlayerBoard>(out var playerBoard, this) ||
                !blackBoard.TryGetGameState<InputBoard, IInputState>(out var inputState, this) ||
                !blackBoard.TryGetGameState<AppBoard, IOperationSettingState>(out _settingState, this)) return;

            playerBoard.RegisterSceneState<IPlayerMovementState>(_state, sceneId);

            // PlayerContactState は EngineAdapterLayer が登録するので、登録を待ち受けて拾う
            _contactStateWaiter = playerBoard.SubscribeStateRegister<IPlayerContactState>(
                () =>
                {
                    if (playerBoard.TryGetSceneState<IPlayerContactState>(out var state, out _))
                    {
                        _contactState = state;
                    }
                },
                invokeIfRegistered: true);

            _subscriptions.Add(inputState.RegisterInput<Vector2>(ActionMaps.Player, PlayerActions.Move, OnMove));
            _subscriptions.Add(inputState.RegisterInput<float>(ActionMaps.Player, PlayerActions.Sprint, OnSprint));
            _subscriptions.Add(inputState.RegisterInput<float>(ActionMaps.Player, PlayerActions.Jump, OnJump));
        }

        /// <summary>
        /// 言葉をつかんでいるかを設定する。つかんでいる間は、次の Step から移動モードを Aiming にして、移動・ジャンプ・突進・打ち上げの要求を捨てる。
        /// </summary>
        /// <param name="isHolding">言葉をつかんでいるか</param>
        public void SetHoldingWord(bool isHolding)
        {
            _isHoldingWord = isHolding;
        }

        /// <summary>
        /// 羽天轟号の使用中かを設定する。使用中は、言葉をつかんでいる間と同じく、移動モードを Aiming にして静止する。
        /// </summary>
        /// <param name="isActive">羽天轟号の使用中か</param>
        public void SetSkyBeamActive(bool isActive)
        {
            _isSkyBeamActive = isActive;
        }

        /// <summary> 突進を始められるか。突進中と、突進の要求を受け付け済みのときと、言葉をつかんでいる間と、羽天轟号の使用中は false </summary>
        public bool CanRush => !_isHoldingWord && !_isSkyBeamActive && !_isRushRequested && _state.Mode != PlayerMoveMode.Warping;

        /// <summary>
        /// 突進する向きを返す。移動入力があれば上下を含む視線の向き、なければ水平な視線の向き。
        /// </summary>
        public Vector3 GetRushDirection()
        {
            var worldInput = ToWorldDirection(_moveInput);
            return worldInput.sqrMagnitude > Mathf.Epsilon ? _viewDirection : _viewForward;
        }

        /// <summary>
        /// 次の Step で、direction の向きへ決めた距離を決めた時間で突進するよう要求する。CanRush が false のときに呼ぶと、言葉をつかんでいる間は捨て、突進中は Step で捨てる。
        /// </summary>
        /// <param name="direction">突進の向き（上下を含む）</param>
        /// <param name="distance">進む距離（m）</param>
        /// <param name="duration">所要時間（秒）</param>
        public void RequestRush(Vector3 direction, float distance, float duration)
        {
            if (direction.sqrMagnitude <= Mathf.Epsilon || distance <= 0f || duration <= 0f) return;

            _isRushRequested = true;
            _rushDirection = direction.normalized;
            _rushDistance = distance;
            _rushDuration = duration;
            _followFlightDuration = 0f;
        }

        /// <summary>
        /// 次の Step で、決めた時間で displacement だけ一直線に飛ぶよう要求する。向きは上下を含む。
        /// 続きの飛びを渡すと、最初の飛びが終わった直後に続けて飛ぶ。
        /// </summary>
        /// <param name="displacement">飛ぶ向きと距離（ワールド空間）</param>
        /// <param name="duration">所要時間（秒）</param>
        /// <param name="followDisplacement">続けて飛ぶ向きと距離。続けないときはゼロ</param>
        /// <param name="followDuration">続けて飛ぶ所要時間（秒）</param>
        public void RequestFlight(Vector3 displacement, float duration, Vector3 followDisplacement,
            float followDuration)
        {
            if (displacement.sqrMagnitude <= Mathf.Epsilon || duration <= 0f) return;

            _isRushRequested = true;
            _rushDirection = displacement.normalized;
            _rushDistance = displacement.magnitude;
            _rushDuration = duration;
            _followFlightDisplacement = followDuration > 0f ? followDisplacement : Vector3.zero;
            _followFlightDuration = followDuration;
        }

        /// <summary>
        /// 位置を直接動かされたことを受け取り、壁走りを抜けて通常の移動に戻す。
        /// 壁に触れたまま動かされても壁走りに入り直さないよう、壁から離れるまで再突入を止める。
        /// </summary>
        public void OnTeleported()
        {
            _state.SetMode(PlayerMoveMode.Normal);
            _isWaitingWallRelease = true;
            _state.SetTargetVelocity(Vector3.zero);
            StopJumpHold();
        }

        /// <summary>
        /// 次の Step でプレイヤーを真上へ打ち上げるよう要求する。同じステップに複数の要求があれば、最も速いものを使う。
        /// </summary>
        /// <param name="speed">上向きの打ち出し速度（m/s）</param>
        public void RequestLaunch(float speed)
        {
            _launchSpeed = Mathf.Max(_launchSpeed, speed);
        }

        /// <summary>
        /// 次の Step でプレイヤーを velocity の向きへ弾くよう要求する。上向きの成分は RequestLaunch と同じく最も速いものを使い、
        /// 水平の成分は同じステップの要求のうち最も速いものを使う。
        /// </summary>
        /// <param name="velocity">打ち出し速度（m/s、ワールド空間）</param>
        public void RequestKnockback(Vector3 velocity)
        {
            _launchSpeed = Mathf.Max(_launchSpeed, velocity.y);

            var horizontal = new Vector3(velocity.x, 0f, velocity.z);
            if (horizontal.sqrMagnitude > _launchHorizontalVelocity.sqrMagnitude) _launchHorizontalVelocity = horizontal;
        }

        /// <summary>
        /// EngineAdapterLayer の FixedUpdate から物理の1ステップごとに呼ばれ、記録済みの入力と視線の向き、
        /// 触れている物から移動モードと目標速度を決めて State に書き込む。
        /// ジャンプ入力・突進と打ち上げの要求はこのステップで処理し、行えなければ捨てる。
        /// 突進中はジャンプ入力も打ち上げも壁走りに入る判定も無視する。打ち上げは壁走りとジャンプより優先する。
        /// </summary>
        /// <param name="viewDirection">ワールド空間の視線の向き</param>
        /// <param name="deltaTime">このステップの経過時間（秒）</param>
        /// <returns>このステップで Rigidbody に与える打ち出し速度。ジャンプか打ち上げをしたステップだけ値を持つ</returns>
        public Vector3? Step(Vector3 viewDirection, float deltaTime)
        {
            if (_settingState == null) return null;

            UpdateViewForward(viewDirection);

            if (_isHoldingWord || _isSkyBeamActive)
            {
                HoldStill();
                return null;
            }

            if (_state.Mode == PlayerMoveMode.Aiming) _state.SetMode(PlayerMoveMode.Normal);

            UpdateJumpHold(deltaTime);

            var worldInput = ToWorldDirection(_moveInput);
            var isJumpRequested = _isJumpRequested;
            _isJumpRequested = false;
            var isRushRequested = _isRushRequested;
            _isRushRequested = false;
            var launchSpeed = _launchSpeed;
            _launchSpeed = 0f;
            var launchHorizontalVelocity = _launchHorizontalVelocity;
            _launchHorizontalVelocity = Vector3.zero;

            if (_state.Mode == PlayerMoveMode.Warping)
            {
                if (_warpTimeRemaining > 0f)
                {
                    AdvanceWarp(deltaTime);
                    return null;
                }

                if (_followFlightDuration > 0f)
                {
                    _rushDirection = _followFlightDisplacement.normalized;
                    _rushDistance = _followFlightDisplacement.magnitude;
                    _rushDuration = _followFlightDuration;
                    _followFlightDuration = 0f;
                    StartRush();
                    AdvanceWarp(deltaTime);
                    return null;
                }

                _state.SetMode(PlayerMoveMode.Normal);
            }
            else if (isRushRequested)
            {
                StartRush();
                AdvanceWarp(deltaTime);
                return null;
            }

            var speed = IsSprinting ? _parameters.SprintSpeed : _parameters.WalkSpeed;

            if (launchSpeed > 0f || launchHorizontalVelocity.sqrMagnitude > 0f)
            {
                // 壁に触れたまま打ち上げられても、壁走りに入って上向きの速度を失わないよう、壁ジャンプ後と同じく再突入を止める
                _state.SetMode(PlayerMoveMode.Normal);
                _isWaitingWallRelease = true;
                _state.SetTargetVelocity(worldInput * speed);
                StopJumpHold();
                return launchHorizontalVelocity + Vector3.up * launchSpeed;
            }

            if (IsGrounded)
            {
                _wallRunTimeRemaining = _parameters.WallRunDuration;
            }

            if (IsTouchingWallInAir)
            {
                _wallNormal = _contactState.WallNormal;
            }
            else
            {
                _isWaitingWallRelease = false;
            }

            if (_state.Mode == PlayerMoveMode.WallRunning)
            {
                if (isJumpRequested)
                {
                    _state.SetMode(PlayerMoveMode.Normal);
                    _isWaitingWallRelease = true;
                    _state.SetTargetVelocity(Vector3.zero);
                    _actionEvents?.Raise(new PlayerActionNotice(PlayerActionKind.WallKicked));
                    StartJumpHold();
                    return CalculateWallJumpVelocity();
                }

                if (ShouldExitWallRun(worldInput, deltaTime))
                {
                    _state.SetMode(PlayerMoveMode.Normal);
                }
            }
            else if (CanEnterWallRun(worldInput))
            {
                _state.SetMode(PlayerMoveMode.WallRunning);
                _wallDetachInputTime = 0f;
                _actionEvents?.Raise(new PlayerActionNotice(PlayerActionKind.WallRunStarted));
            }

            if (_state.Mode == PlayerMoveMode.WallRunning)
            {
                // 壁が途切れたら、壁走りのままその場にとどまる
                var wallRunSpeed = IsSprinting ? _parameters.WallRunSprintSpeed : _parameters.WallRunWalkSpeed;
                _state.SetTargetVelocity(IsTouchingWallInAir ? ProjectOnWall(worldInput) * wallRunSpeed : Vector3.zero);
                return null;
            }

            _state.SetTargetVelocity(worldInput * speed);

            if (!isJumpRequested || !IsGrounded) return null;

            _actionEvents?.Raise(new PlayerActionNotice(PlayerActionKind.Jumped));
            StartJumpHold();
            return Vector3.up * CalculateJumpSpeed();
        }

        /// <summary>
        /// 言葉をつかんでいる間の Step。進行中の突進は打ち切り、受け付けた要求を捨てて、移動モードを Aiming にして目標速度を0にする。
        /// </summary>
        private void HoldStill()
        {
            _isJumpRequested = false;
            _isRushRequested = false;
            _launchSpeed = 0f;
            _warpTimeRemaining = 0f;
            _followFlightDuration = 0f;
            StopJumpHold();
            _state.SetMode(PlayerMoveMode.Aiming);
            _state.SetTargetVelocity(Vector3.zero);
        }

        /// <summary>
        /// 壁走りに入れるかどうか。足元の近くに地面がなく、空中で壁に触れ、前向きの移動入力と壁の法線のなす角が WallDetachAngle より大きく、
        /// 持ち時間が残り、壁ジャンプ後の待ちが解けているときに入れる。
        /// </summary>
        private bool CanEnterWallRun(Vector3 worldInput)
        {
            return !IsNearGround && IsTouchingWallInAir && _moveInput.y > 0f && !IsPullingAwayFromWall(worldInput) &&
                   _wallRunTimeRemaining > 0f && !_isWaitingWallRelease;
        }

        /// <summary>
        /// 入力が壁から離れる向き（壁の法線とのなす角が WallDetachAngle 以下）かどうか。入力が0のときは false。
        /// </summary>
        private bool IsPullingAwayFromWall(Vector3 worldInput)
        {
            return worldInput.sqrMagnitude > Mathf.Epsilon &&
                   Vector3.Angle(worldInput, _wallNormal) <= _parameters.WallDetachAngle;
        }

        /// <summary>
        /// 壁走りの持ち時間と、壁から離れようとする入力の継続時間を進め、壁走りを抜けるかどうかを返す。
        /// 着地したとき、持ち時間が尽きたとき、壁から離れる向きの入力が一定時間続いたときに抜ける。
        /// </summary>
        private bool ShouldExitWallRun(Vector3 worldInput, float deltaTime)
        {
            if (IsGrounded) return true;

            _wallRunTimeRemaining -= deltaTime;
            if (_wallRunTimeRemaining <= 0f)
            {
                _wallRunTimeRemaining = 0f;
                return true;
            }

            _wallDetachInputTime = IsPullingAwayFromWall(worldInput) ? _wallDetachInputTime + deltaTime : 0f;
            return _wallDetachInputTime >= _parameters.WallDetachTime;
        }

        /// <summary>
        /// 入力から壁の法線方向の成分を取り除き、壁の面に沿った水平な向きにする。長さは残った成分の長さになる。
        /// </summary>
        private Vector3 ProjectOnWall(Vector3 worldInput)
        {
            return Vector3.ProjectOnPlane(worldInput, _wallNormal);
        }

        /// <summary>
        /// 壁ジャンプの打ち出し速度を求める。
        /// 水平方向は、向いている方向（視線の水平な向き）。壁のほうを向いているときは、壁の法線で折り返して外へ向ける。
        /// 上向きの速度はジャンプと同じ。
        /// </summary>
        private Vector3 CalculateWallJumpVelocity()
        {
            var wallNormal = _wallNormal;

            var horizontalDirection = Vector3.Dot(_viewForward, wallNormal) < 0f
                ? Vector3.Reflect(_viewForward, wallNormal)
                : _viewForward;

            return horizontalDirection * _parameters.WallJumpHorizontalSpeed + Vector3.up * CalculateJumpSpeed();
        }

        /// <summary>
        /// 突進を始める。移動モードを Warping にし、要求された向きと距離、所要時間から速度を決める。
        /// </summary>
        private void StartRush()
        {
            _warpVelocity = _rushDirection * (_rushDistance / _rushDuration);
            _warpTimeRemaining = _rushDuration;
            _state.SetMode(PlayerMoveMode.Warping);
        }

        /// <summary>
        /// 突進を1ステップ分進める。目標速度に突進の速度を書き込み、残りの所要時間を減らす。
        /// 残りの所要時間がステップの経過時間より短いときは、進む距離が揃うよう速度をその割合だけ落とす。
        /// </summary>
        private void AdvanceWarp(float deltaTime)
        {
            var ratio = deltaTime > 0f ? Mathf.Clamp01(_warpTimeRemaining / deltaTime) : 0f;
            _state.SetTargetVelocity(_warpVelocity * ratio);
            _warpTimeRemaining -= deltaTime;
        }

        /// <summary>
        /// ジャンプの高さから、ジャンプの初速を求める。高さ h まで上がる初速は v = √(2gh)。
        /// </summary>
        private float CalculateJumpSpeed()
        {
            return Mathf.Sqrt(2f * Mathf.Abs(Physics.gravity.y) * _parameters.JumpHeight);
        }

        /// <summary>
        /// ジャンプの長押しの効果を進める。通常の移動でボタンを押し続けていて、時間が残っている間だけ長押し中にする。
        /// </summary>
        private void UpdateJumpHold(float deltaTime)
        {
            if (!_isJumpHeld || _state.Mode != PlayerMoveMode.Normal || _jumpHoldRemaining <= 0f)
            {
                StopJumpHold();
                return;
            }

            _jumpHoldRemaining -= deltaTime;
            _state.SetJumpHolding(_jumpHoldRemaining > 0f);
        }

        /// <summary>
        /// ジャンプの長押しの効果を始める。ボタンを押し続けている間、JumpHoldTime だけ続く。
        /// </summary>
        private void StartJumpHold()
        {
            _jumpHoldRemaining = _parameters.JumpHoldTime;
            _state.SetJumpHolding(_isJumpHeld && _jumpHoldRemaining > 0f);
        }

        private void StopJumpHold()
        {
            _jumpHoldRemaining = 0f;
            _state.SetJumpHolding(false);
        }

        private void OnMove(InputContext<Vector2> context)
        {
            _moveInput = context.Phase == InputPhase.Canceled
                ? Vector2.zero
                : Vector2.ClampMagnitude(context.Value, 1f);

            if (_moveInput.sqrMagnitude <= Mathf.Epsilon)
            {
                _isSprintToggled = false;
            }
        }

        private void OnSprint(InputContext<float> context)
        {
            switch (context.Phase)
            {
                case InputPhase.Performed:
                    _isSprintHeld = true;
                    _isSprintToggled = !_isSprintToggled;
                    break;
                case InputPhase.Canceled:
                    _isSprintHeld = false;
                    break;
            }
        }

        private void OnJump(InputContext<float> context)
        {
            switch (context.Phase)
            {
                case InputPhase.Performed:
                    _isJumpRequested = true;
                    _isJumpHeld = true;
                    break;
                case InputPhase.Canceled:
                    _isJumpHeld = false;
                    break;
            }
        }

        /// <summary>
        /// 視線の向きを上下を含めて保持し、水平面へ投影した向きも保持する。投影した向きは水平成分があるときだけ更新する。
        /// </summary>
        private void UpdateViewForward(Vector3 viewDirection)
        {
            if (viewDirection.sqrMagnitude > 1e-6f) _viewDirection = viewDirection.normalized;

            viewDirection.y = 0f;
            if (viewDirection.sqrMagnitude < 1e-6f) return;

            _viewForward = viewDirection.normalized;
        }

        /// <summary>
        /// 入力（x が右、y が前）を、水平な視線の向きを前方としたワールド方向へ変換する。長さは入力の長さを保つ。
        /// </summary>
        private Vector3 ToWorldDirection(Vector2 input)
        {
            var right = Vector3.Cross(Vector3.up, _viewForward);
            return right * input.x + _viewForward * input.y;
        }

        public void Dispose()
        {
            foreach (var subscription in _subscriptions)
            {
                subscription.Dispose();
            }

            _subscriptions.Clear();
            _contactStateWaiter?.Dispose();
        }
    }

    /// <summary>
    /// プレイヤーの移動に、突進・飛び移り・打ち上げ・弾き飛ばし・言葉をつかんでいる間・羽天轟号の間を伝える操作面。
    /// スキル・羽天轟号・飛び移り・言葉の投擲と、敵・ボスの攻撃が使う。
    /// </summary>
    public interface IPlayerMovementController
    {
        /// <summary> 言葉をつかんでいるか </summary>
        bool IsHoldingWord { get; }

        /// <summary> 突進（と飛び移り）を始められるか </summary>
        bool CanRush { get; }

        /// <summary>
        /// 言葉をつかんでいるかを設定する。
        /// </summary>
        /// <param name="isHolding">つかんでいるか</param>
        void SetHoldingWord(bool isHolding);

        /// <summary>
        /// 羽天轟号を撃っているかを設定する。
        /// </summary>
        /// <param name="isActive">撃っているか</param>
        void SetSkyBeamActive(bool isActive);

        /// <summary>
        /// 突進する向きを返す。
        /// </summary>
        Vector3 GetRushDirection();

        /// <summary>
        /// 次の Step で、direction の向きへ決めた距離を決めた時間で突進するよう要求する。
        /// </summary>
        /// <param name="direction">突進の向き（上下を含む）</param>
        /// <param name="distance">進む距離（m）</param>
        /// <param name="duration">所要時間（秒）</param>
        void RequestRush(Vector3 direction, float distance, float duration);

        /// <summary>
        /// 次の Step で、決めた時間で displacement だけ一直線に飛ぶよう要求する。
        /// </summary>
        /// <param name="displacement">飛ぶ向きと距離（ワールド空間）</param>
        /// <param name="duration">所要時間（秒）</param>
        /// <param name="followDisplacement">続けて飛ぶ向きと距離。続けないときはゼロ</param>
        /// <param name="followDuration">続けて飛ぶ所要時間（秒）</param>
        void RequestFlight(Vector3 displacement, float duration, Vector3 followDisplacement, float followDuration);

        /// <summary>
        /// 位置を直接動かしたあとに呼ぶ。壁走りを抜けて通常の移動に戻す。
        /// </summary>
        void OnTeleported();

        /// <summary>
        /// 次の Step でプレイヤーを真上へ打ち上げるよう要求する。
        /// </summary>
        /// <param name="speed">上向きの打ち出し速度（m/s）</param>
        void RequestLaunch(float speed);

        /// <summary>
        /// 次の Step でプレイヤーを velocity の向きへ弾くよう要求する。
        /// </summary>
        /// <param name="velocity">打ち出し速度（m/s、ワールド空間）</param>
        void RequestKnockback(Vector3 velocity);
    }
