using Kizami.Application;
using Kizami.BlackBoard;
using Kizami.EngineAdapter;
using UnityEngine;
using UnityEngine.InputSystem;
using UsefulToolkit.Attributes;
using UsefulToolkit.BlackBoard.BlackBoard;
using UsefulToolkit.Initialization;
using UsefulToolkit.Utility;

namespace Kizami.Initialization
{
    /// <summary>
    /// 操作に関わる設定（OperationSettingState）を生成し、書き込み面（IOperationSettingController）を配る Initializer。
    /// 設定はシーンを跨いで保たれるので、常駐シーンへ置いて一度だけ生成する。
    /// </summary>
    [InitializeOrder(InitializeOrderConst.InitializerEarly - 10)]
    public sealed class OperationSettingInitializer : InitializerBase
    {
        [SerializeField]
        [Tooltip("ダッシュ入力の受け付け方の初期値")]
        private SprintInputMode _sprintInputMode = SprintInputMode.Hold;

        [SerializeField]
        [Tooltip("かけらと文字をつかんで投げる入力の受け付け方の初期値")]
        private GrabInputMode _grabInputMode = GrabInputMode.Toggle;

        [SerializeField, Range(1f, 90f)]
        [Tooltip("切断面の回転入力（ホイール 1 段）1 回あたりの回転角度（度）の初期値")]
        private float _cutRotateStepAngle = 15f;

        [SerializeField]
        [Tooltip("キーの割り当てを変える InputActionAsset。常駐シーンの InputDispatcher に割り当てているものと同じ物。空ならキーコンフィグを使えない")]
        private InputActionAsset _inputActions;

        private OperationSettingService _settingService;

        public override void Initialize(IBlackBoard blackBoard)
        {
            _settingService.Initialize(blackBoard);

            base.Initialize(blackBoard);
        }

        private void Awake()
        {
            _settingService = new OperationSettingService(_sprintInputMode, _grabInputMode, _cutRotateStepAngle);
            AutoGenerated.UsefulToolkitPersistentCompositor.TryRegisterContent<IOperationSettingController>(
                _settingService);

            if (_inputActions == null) return;

            var rebindAdapter = new InputRebindAdapter(_inputActions, _settingService);
            rebindAdapter.ApplySaved();
            AutoGenerated.UsefulToolkitPersistentCompositor.TryRegisterContent(rebindAdapter);
        }
    }
}
