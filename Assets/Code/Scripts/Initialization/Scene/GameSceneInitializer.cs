using Cysharp.Threading.Tasks;
using Kizami.Application;
using Kizami.External;
using UnityEngine;
using UsefulToolkit.Attributes;
using UsefulToolkit.BlackBoard.BlackBoard;
using UsefulToolkit.BlackBoard.Logger;
using UsefulToolkit.External.Scene;
using UsefulToolkit.Initialization;
using UsefulToolkit.Utility;

namespace Kizami.Initialization
{
    /// <summary>
    /// 進行（GameProgressService）とシーン遷移の操作面を組み立て、起動時にアウトゲームへ遷移する Initializer。常駐シーンへ置く。
    /// </summary>
    [InitializeOrder(InitializeOrderConst.Initializer)]
    public sealed class GameSceneInitializer : InitializerBase
    {
        private readonly GameProgressService _progressService = new();
        private readonly GameSceneController _sceneController = new();

        [SerializeField]
        [Tooltip("アウトゲームで読み込むシーングループ。")]
        private SceneGroupDataBase _outGameGroup;

        [SerializeField]
        [Tooltip("アウトゲームで選べるステージ。ステージの番号はこの並びの位置。")]
        private StageData[] _stages;

        [SerializeField]
        [Tooltip("アウトゲームで装備できるスキル。スキルの番号はこの並びの位置。初めは先頭から順に装備枠へ装備する。")]
        private SkillData[] _skills;

        [SerializeField, Min(0)]
        [Tooltip("ステージを初めてクリアしたときに得る通貨の量。仕様でステージによらず同じ量。")]
        private int _firstClearReward = 100;

        [SerializeField]
        [Tooltip("起動時にアウトゲームへ自動で遷移する。")]
        private bool _transitionOnStart = true;

        public override void Initialize(IBlackBoard blackBoard)
        {
            if (_outGameGroup == null || _outGameGroup.GroupData == null)
            {
                UsefulLogger.LogError("アウトゲームのシーングループが設定されていない為、シーン遷移を初期化できません。", this);
                return;
            }

            _progressService.Initialize(blackBoard, _stages, _skills, _firstClearReward);
            if (!_sceneController.Initialize(blackBoard, _outGameGroup.GroupData, _progressService)) return;

            base.Initialize(blackBoard);

            if (_transitionOnStart)
            {
                _sceneController.StartGameAsync(destroyCancellationToken).Forget();
            }
        }

        private void Awake()
        {
            AutoGenerated.UsefulToolkitPersistentCompositor.TryRegisterContent<IGameSceneController>(_sceneController);
            AutoGenerated.UsefulToolkitPersistentCompositor.TryRegisterContent(_progressService);
        }
    }
}
