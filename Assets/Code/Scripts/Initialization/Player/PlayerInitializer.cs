namespace Kizami.Initialization
{
    /// <summary>
    /// プレイヤーの移動・視点・HP・近接切断・チャージ・スキル・スローモード・投擲まわり（Service / State / Adapter）を生成して繋ぐ配線役。インゲームのシーンへ置く。
    /// 投擲の Adapter は、かけらの Adapter の管理から外せたかけらだけをつかむ。
    /// 操作系ごとの視点の回転のさせ方の違いは、シーンへ置く PlayerMovementAdapterBase の派生が吸収する。
    /// </summary>
    public sealed class PlayerInitializer : InitializerBase, IInjectable<ITimeScaleController>, IInjectable<GameProgressService>
    {
        private readonly PlayerHealthService _healthService = new();
        private readonly PlayerMovementService _movementService = new();
        private readonly PlayerActionEvents _actionEvents = new();
        private readonly PlayerSkillEffectEvents _effectEvents = new();

        [SerializeField]
        [Tooltip("プレイヤーの移動・HP・近接切断・チャージのパラメータ")]
        private PlayerParameterData _parameters;

        [SerializeField] private PlayerMovementAdapterBase _movementAdapter;
        [SerializeField] private PlayerCameraAdapterBase _cameraAdapter;
        [SerializeField] private MeleeCutPreviewAdapter _meleeCutPreviewAdapter;
        [SerializeField] private MeleeCutAdapter _meleeCutAdapter;
        [SerializeField] private FragmentOrbAdapter _fragmentOrbAdapter;
        [SerializeField] private EnemyEnergyAdapter _enemyEnergyAdapter;
        [SerializeField] private EnemySpawnAdapter _enemySpawnAdapter;
        [SerializeField] private VoxelDestructionAdapter _voxelDestructionAdapter;
        [SerializeField] private FragmentThrowAdapter _fragmentThrowAdapter;
        [SerializeField] private VoxelMoundAdapter _voxelMoundAdapter;

        [SerializeField]
        [Tooltip("一人称の腕を動かす Adapter。未設定なら腕は動かさない（VR など腕を置かない操作系）")]
        private PlayerArmAdapter _armAdapter;

        [SerializeField]
        [Tooltip("火術・崩爆の爆弾を投げる Adapter。未設定なら、既定の値でこの GameObject に付ける")]
        private BombThrowAdapter _bombThrowAdapter;

        [SerializeField]
        [Tooltip("視線の先の飛び移りの目印を探す Adapter。未設定なら、既定の値でこの GameObject に付ける")]
        private FlightAdapter _flightAdapter;

        [SerializeField]
        [Tooltip("火術奥義・羽天轟号の上昇と戻りでプレイヤーの位置を動かす Adapter。未設定なら、既定の値でこの GameObject に付ける")]
        private SkyBeamAdapter _skyBeamAdapter;

        [SerializeField]
        [Tooltip("アウトゲームを通さずに始めたとき（インゲームのシーンから直接再生したときなど）に、スキル 1〜3 の枠に装備するスキル。空きの枠は None にする")]
        private SkillData[] _equippedSkills = new SkillData[SkillService.SLOT_COUNT];

        private PlayerEnhanceService _enhanceService;
        private PlayerLookService _lookService;
        private MeleeCutService _meleeCutService;
        private ChargeService _chargeService;
        private SkillService _skillService;
        private SlowModeService _slowModeService;
        private FlightService _flightService;
        private SkyBeamService _skyBeamService;
        private FragmentThrowService _fragmentThrowService;
        private ITimeScaleController _timeScaleController;
        private GameProgressService _progressService;

        public override void Initialize(IBlackBoard blackBoard)
        {
            if (!HasRequiredReferences())
            {
                base.Initialize(blackBoard);
                return;
            }

            if (_timeScaleController == null)
            {
                UsefulLogger.LogError("ITimeScaleController を受け取れなかった為、スローモードを使えません。", this);
            }

            var sceneId = gameObject.scene.buildIndex;

            // 発行側の Service が使う前に、購読面を登録しておく
            if (blackBoard.TryGetEventBoard<PlayerEventBoard>(out var eventBoard, this))
            {
                eventBoard.RegisterSceneEvent<IPlayerActionEvents>(_actionEvents, sceneId);
                eventBoard.RegisterSceneEvent<IPlayerSkillEffectEvents>(_effectEvents, sceneId);
            }

            _movementService.Initialize(blackBoard, _parameters, _actionEvents, sceneId);

            // PlayerHealthService は PlayerMovementState を取得する為、PlayerMovementService の初期化より後に初期化する。
            // SkillService が PlayerHealthState を取得する為、SkillService の生成より前に初期化する
            _healthService.Initialize(blackBoard, _parameters, sceneId);

            _enhanceService = new PlayerEnhanceService(blackBoard, sceneId);
            _lookService = new PlayerLookService(blackBoard, sceneId);
            StageSelection.TryGetSelectedStage(_progressService, out var selectedStage);
            _chargeService = new ChargeService(blackBoard, _parameters, selectedStage, sceneId);

            _fragmentOrbAdapter.Initialize(_chargeService.AddFragments);
            _enemyEnergyAdapter.Initialize(_chargeService.AddCollapsedEnemies);
            _meleeCutAdapter.Initialize(DistributeCutResults, _armAdapter);

            // F は、飛び移れるときは飛び移り、そうでなければスローモードになる為、FlightService を先に生成して渡す
            _flightService = new FlightService(blackBoard, _movementService, _parameters.FlightSpeed,
                () => _movementAdapter.BodyBounds.center, _effectEvents, sceneId);
            if (_flightAdapter == null) _flightAdapter = gameObject.AddComponent<FlightAdapter>();
            _flightAdapter.Initialize(_flightService.SetCandidate);

            // SlowModeService は ChargeState を取得する為、ChargeService の生成より後に生成する
            _slowModeService = new SlowModeService(blackBoard, _parameters, _chargeService, _timeScaleController,
                _flightService.TryFly, sceneId);
            // MeleeCutService が羽天轟号の使用中かを見る為、MeleeCutService の生成より前に生成する
            if (_skyBeamAdapter == null) _skyBeamAdapter = gameObject.AddComponent<SkyBeamAdapter>();
            _skyBeamService = new SkyBeamService(_movementService, _chargeService, _actionEvents, _skyBeamAdapter.Begin,
                _skyBeamAdapter.Stop);
            _skyBeamAdapter.Initialize(_movementAdapter, _skyBeamService.OnFinished, _skyBeamService.TryContinue,
                _voxelDestructionAdapter.CarveSkyBeamAt, _enemySpawnAdapter.DefeatInRadius);

            // MeleeCutService が VoxelMoundState を取得する為、MeleeCutService の生成より前に初期化する
            _voxelMoundAdapter.Initialize(blackBoard, _chargeService.TryConsume, _enemySpawnAdapter.WatchPiece,
                _enemySpawnAdapter.RefreshRegion);
            _meleeCutService = new MeleeCutService(blackBoard, _parameters, _enhanceService, _meleeCutAdapter.Swing,
                _slowModeService.TryUseCut, _skyBeamService, _actionEvents, sceneId);
            if (_bombThrowAdapter == null) _bombThrowAdapter = gameObject.AddComponent<BombThrowAdapter>();
            _bombThrowAdapter.Initialize(blackBoard, _voxelDestructionAdapter.CarveExplosionAt);
            _voxelDestructionAdapter.Initialize(blackBoard);

            _skillService = new SkillService(blackBoard, StageSelection.GetEquippedSkillsOrDefault(_progressService, _equippedSkills),
                _chargeService, _enhanceService, _healthService, () => _movementAdapter.BodyBounds, _voxelMoundAdapter.Begin,
                _voxelMoundAdapter.End, _movementService, _meleeCutService, _skyBeamService, _actionEvents, _effectEvents, sceneId);

            _fragmentThrowAdapter.Initialize();

            _fragmentThrowService = new FragmentThrowService(blackBoard, _parameters, _movementService,
                _fragmentThrowAdapter.TryGrabWord, () => _fragmentThrowAdapter.IsHolding, _fragmentThrowAdapter.TryThrow);

            // 以降の Adapter は Service が登録した State を取得する為、Service の生成より後に初期化する
            _movementAdapter.Initialize(blackBoard, _movementService.Step);

            // カメラの上下方向反映は操作系によっては使わない（例: VR は HMD の姿勢が担う）為、未設定でもエラーにしない
            if (_cameraAdapter != null)
            {
                _cameraAdapter.Initialize(blackBoard);
            }

            _meleeCutPreviewAdapter.Initialize(blackBoard);
            if (_armAdapter != null) _armAdapter.Initialize(blackBoard);

            base.Initialize(blackBoard);
        }

        /// <summary>
        /// 必須の参照がすべて設定されているかを返す。足りないものは、すべてエラーログに出す。
        /// </summary>
        private bool HasRequiredReferences()
        {
            var hasAll = this.IsAssigned(_parameters, nameof(PlayerParameterData));
            hasAll &= this.IsAssigned(_movementAdapter, nameof(PlayerMovementAdapterBase));
            hasAll &= this.IsAssigned(_meleeCutPreviewAdapter, nameof(MeleeCutPreviewAdapter));
            hasAll &= this.IsAssigned(_meleeCutAdapter, nameof(MeleeCutAdapter));
            hasAll &= this.IsAssigned(_fragmentOrbAdapter, nameof(FragmentOrbAdapter));
            hasAll &= this.IsAssigned(_enemyEnergyAdapter, nameof(EnemyEnergyAdapter));
            hasAll &= this.IsAssigned(_enemySpawnAdapter, nameof(EnemySpawnAdapter));
            hasAll &= this.IsAssigned(_voxelDestructionAdapter, nameof(VoxelDestructionAdapter));
            hasAll &= this.IsAssigned(_fragmentThrowAdapter, nameof(FragmentThrowAdapter));
            hasAll &= this.IsAssigned(_voxelMoundAdapter, nameof(VoxelMoundAdapter));
            return hasAll;
        }

        /// <summary>
        /// 切断の結果を、敵の Adapter、かけらの Adapter の順に渡す。
        /// 敵の Adapter は体に残す側のかけらをプールへ返して非アクティブにするので、かけらの Adapter はそれを管理に加えない。
        /// </summary>
        private void DistributeCutResults(MultiCutResult[] results, Plane plane)
        {
            _enemySpawnAdapter.ReceiveCutResults(results, plane);
            _fragmentOrbAdapter.ReceiveCutResults(results);
        }

        private void Awake()
        {
            InGameCompositor.TryRegisterContent(_healthService);
            InGameCompositor.TryRegisterContent(_movementService);
        }

        private void OnDestroy()
        {
            _movementService.Dispose();
            _healthService.Dispose();
            _lookService?.Dispose();
            _meleeCutService?.Dispose();
            _skillService?.Dispose();
            _slowModeService?.Dispose();
            _fragmentThrowService?.Dispose();
        }

        public void Inject(ITimeScaleController instance)
        {
            _timeScaleController = instance;
        }

        public void Inject(GameProgressService instance)
        {
            _progressService = instance;
        }
    }
